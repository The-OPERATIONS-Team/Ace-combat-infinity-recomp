#!/usr/bin/env python3
import re, sys, collections

FMT_BITS = {"RRR":4, "RI18":7, "RI10":8, "RI16":9, "RR":11, "RI7":11}

def parse(path):
    rows=[]
    for line in open(path):
        m=re.match(r'^\s+[0-9a-f]+:\t([0-9a-f ]+)\t([a-z][a-z0-9]*)\t?(.*)$', line)
        if not m: continue
        bs=m.group(1).split()
        if len(bs)!=4: continue
        insn=int(bs[0],16)<<24|int(bs[1],16)<<16|int(bs[2],16)<<8|int(bs[3],16)
        ops=m.group(3).split('#')[0].strip()
        rows.append((insn,m.group(2),ops))
    return rows

def candidate_formats(ops):
    regs=ops.count('$')
    has_disp = bool(re.search(r'\$\d+\s*\(', ops)) or bool(re.search(r'-?\d+\(\$', ops))
    has_imm = bool(re.search(r'(^|,)\s*-?\d', ops)) or ('0x' in ops)
    if regs>=4: return ["RRR"]
    if has_disp: return ["RI7","RI10"]
    if regs==0 and (has_imm or ops==''):
        return ["RI16","RI18","RR"]
    if has_imm:
        if regs>=2: return ["RI10","RI7"]
        return ["RI16","RI18"]
    return ["RR"]

RI7_MNEMS = {"shlhi","shli","shlqbii","shlqbyi","rothi","roti","rotqbyi","rotqbii",
             "rothmi","rotmi","rotqmbyi","rotqmbii","rotmahi","rotmai",
             "cbd","chd","cwd","cdd","dftsv"}

def main():
    rows=parse("gt1.txt")
    bymn=collections.defaultdict(list)
    for insn,mn,ops in rows: bymn[mn].append((insn,ops))
    table={}
    unresolved=[]
    for mn,samples in sorted(bymn.items()):
        cand=set()
        for insn,ops in samples:
            for f in candidate_formats(ops): cand.add(f)
        if mn not in RI7_MNEMS: cand.discard("RI7")
        best=None
        for f in sorted(cand, key=lambda x:-FMT_BITS[x]):
            nb=FMT_BITS[f]
            vals={ insn>>(32-nb) for insn,_ in samples }
            if len(vals)==1:
                v=next(iter(vals))
                if best is None: best=(v,nb,f)
        if best is None: unresolved.append(mn)
        else: table[mn]=best
    with open("spu_decode_table.inc","w") as o:
        o.write("// auto-generated by gen_spu_table.py from spu-lv2-objdump ground truth\n")
        o.write("// {opcode value, nbits, format, mnemonic}\n")
        for mn,(v,nb,f) in sorted(table.items(), key=lambda kv:(-kv[1][1],kv[1][0])):
            o.write('{0x%x,%d,%s,"%s"},\n'%(v,nb,f,mn))
    print("resolved %d mnemonics -> spu_decode_table.inc"%len(table))
    if unresolved: print("UNRESOLVED:",unresolved)
    print("formats:",collections.Counter(f for _,_,f in table.values()))

main()
